import pool from "../config/database.js";

export async function initializeUserTable() {
  await pool.query(`
    CREATE TABLE IF NOT EXISTS users (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      name VARCHAR(120) NOT NULL,
      email VARCHAR(320) NOT NULL UNIQUE,
      password_hash TEXT NOT NULL,
      reset_token_hash TEXT,
      reset_token_expires_at TIMESTAMPTZ,
      created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
    )
  `);
}

export async function createUser({ name, email, passwordHash }) {
  const { rows } = await pool.query(
    `INSERT INTO users (name, email, password_hash)
     VALUES ($1, $2, $3)
     RETURNING id, name, email, created_at`,
    [name, email, passwordHash],
  );
  return rows[0];
}

export async function findUserByEmail(email) {
  const { rows } = await pool.query(
    `SELECT id, name, email, password_hash
     FROM users
     WHERE email = $1`,
    [email],
  );
  return rows[0] ?? null;
}

export async function listUsers() {
  const { rows } = await pool.query(
    `SELECT id, name, email, created_at
     FROM users
     ORDER BY id ASC`,
  );
  return rows;
}

export async function savePasswordResetToken(email, tokenHash, expiresAt) {
  await pool.query(
    `UPDATE users
     SET reset_token_hash = $2, reset_token_expires_at = $3
     WHERE email = $1`,
    [email, tokenHash, expiresAt],
  );
}

export async function clearPasswordResetToken(email) {
  await pool.query(
    `UPDATE users
     SET reset_token_hash = NULL, reset_token_expires_at = NULL
     WHERE email = $1`,
    [email],
  );
}

export async function resetPassword(tokenHash, passwordHash) {
  const { rows } = await pool.query(
    `UPDATE users
     SET password_hash = $2,
         reset_token_hash = NULL,
         reset_token_expires_at = NULL
     WHERE reset_token_hash = $1
       AND reset_token_expires_at > NOW()
     RETURNING id`,
    [tokenHash, passwordHash],
  );
  return rows.length > 0;
}
