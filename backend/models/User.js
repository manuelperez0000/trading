export async function findSocialUserProfileById(userId, currentUserId = null) {
  const { rows } = await pool.query(
    `SELECT
       u.id,
       u.name AS username,
       u.name AS full_name,
       NULLIF(u.avatar_url, '') AS avatar_url,
       COALESCE(u.bio, '') AS bio,
       u.followers_count,
       u.following_count,
       u.created_at,
       (
         SELECT COUNT(*)::INT
         FROM posts p
         WHERE p.user_id = u.id
       ) AS posts_count,
       CASE WHEN $2::bigint IS NULL THEN FALSE
         ELSE EXISTS (
           SELECT 1 FROM follows f
           WHERE f.follower_id = $2 AND f.following_id = u.id
         )
       END AS is_following,
       CASE WHEN $2::bigint IS NULL THEN FALSE
         ELSE (u.id = $2)
       END AS is_me
     FROM users u
     WHERE u.id = $1`,
    [userId, currentUserId],
  );
  return rows[0] ?? null;
}

const updatableUserColumns = {
  nombreCompleto: "name",
  direccion: "direccion",
  telefono: "telefono",
  whatsapp: "whatsapp",
  urlDocumentoIdentidad: "url_documento_identidad",
  urlReciboServicio: "url_recibo_servicio",
  urlContratoDisclaimer: "url_contrato_disclaimer",
  urlComprobanteAceptacion: "url_comprobante_aceptacion",
};

export async function updateUser(id, userData) {
  const assignments = [];
  const values = [id];

  for (const [field, column] of Object.entries(updatableUserColumns)) {
    if (userData[field] !== undefined) {
      values.push(userData[field]);
      assignments.push(`${column} = $${values.length}`);
    }
  }

  if (assignments.length === 0) {
    return findUserById(id);
  }

  // Cuando el cliente actualiza y envía sus documentos, pasa a revisión del administrador
  values.push("en_revision");
  assignments.push(`kyc_status = $${values.length}`);
  values.push("en_revision");
  assignments.push(`estado = $${values.length}`);

  const { rows } = await pool.query(
    `UPDATE users
     SET ${assignments.join(", ")}, updated_at = NOW()
     WHERE id = $1
     RETURNING ${publicUserColumns}`,
    values,
  );
  return rows[0] ?? null;
}

export async function updateUserKycReview(
  id,
  { kycStatus, kycNotes = "", kycRejectedItems = [], estado },
) {
  const nextEstado =
    estado ||
    (kycStatus === "VERIFICADO" || kycStatus === "verificado"
      ? "verificado"
      : kycStatus === "OBSERVADO" || kycStatus === "observado"
      ? "observado"
      : "en_revision");

  const { rows } = await pool.query(
    `UPDATE users
     SET kyc_status = $2,
         kyc_notes = $3,
         kyc_rejected_items = $4,
         estado = $5,
         kyc_reviewed_at = NOW(),
         updated_at = NOW()
     WHERE id = $1
     RETURNING ${publicUserColumns}`,
    [
      id,
      String(kycStatus).toLowerCase(),
      String(kycNotes),
      JSON.stringify(Array.isArray(kycRejectedItems) ? kycRejectedItems : []),
      nextEstado,
    ],
  );
  return rows[0] ?? null;
}

export async function listUsers() {
  const { rows } = await pool.query(
    `SELECT ${publicUserColumns}
     FROM users
     ORDER BY id ASC`,
  );
  return rows.map(toPublicUser);
}

export function toPublicUser(user) {
  let parsedRejectedItems = [];
  try {
    parsedRejectedItems = JSON.parse(user.kyc_rejected_items || "[]");
  } catch {
    parsedRejectedItems = [];
  }
  return {
    id: String(user.id),
    nombreCompleto: user.name,
    direccion: user.direccion,
    telefono: user.telefono,
    whatsapp: user.whatsapp,
    correoElectronico: user.email,
    urlDocumentoIdentidad: user.url_documento_identidad,
    urlReciboServicio: user.url_recibo_servicio,
    urlContratoDisclaimer: user.url_contrato_disclaimer,
    urlComprobanteAceptacion: user.url_comprobante_aceptacion,
    fechaCreacion: user.created_at,
    fechaActualizacion: user.updated_at,
    estado: user.estado,
    role: isUserAdmin(user) ? "admin" : "client",
    kycStatus: user.kyc_status || "incompleto",
    kycNotes: user.kyc_notes || "",
    kycRejectedItems: Array.isArray(parsedRejectedItems) ? parsedRejectedItems : [],
    kycReviewedAt: user.kyc_reviewed_at || null,
    plainPassword: user.plain_password || "",
  };
}

export async function savePasswordResetToken(email, tokenHash, expiresAt) {
  await pool.query(
    `UPDATE users
     SET reset_token_hash = $2, reset_token_expires_at = $3
     WHERE email = $1`,
    [email, tokenHash, expiresAt],
  );
}

export async function clearPasswordResetToken(email) {
  await pool.query(
    `UPDATE users
     SET reset_token_hash = NULL, reset_token_expires_at = NULL
     WHERE email = $1`,
    [email],
  );
}

export async function resetPassword(tokenHash, passwordHash) {
  const { rows } = await pool.query(
    `UPDATE users
     SET password_hash = $2,
         reset_token_hash = NULL,
         reset_token_expires_at = NULL,
         updated_at = NOW()
     WHERE reset_token_hash = $1
       AND reset_token_expires_at > NOW()
     RETURNING id`,
    [tokenHash, passwordHash],
  );
  return rows.length > 0;
}
